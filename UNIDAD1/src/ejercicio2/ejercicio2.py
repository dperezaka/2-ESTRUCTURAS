"""
Descripción: Crear un programa que realice las cuatro operaciones aritméticas básicas (suma, resta, multiplicación y división)
"""

numero1 = 10
numero2 = 2

print(f"Numero 1 {numero1} + numero 2 {numero2} es {numero1+numero2}")
print(f"Numero 1 {numero1} - numero 2 {numero2} es {numero1-numero2}")
print(f"Numero 1 {numero1} * numero 2 {numero2} es {numero1*numero2}")
print(f"Numero 1 {numero1} / numero 2 {numero2} es {numero1/numero2}")
